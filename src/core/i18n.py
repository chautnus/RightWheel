def _merge_extra_locales() -> None:
    """Merge extended translation dictionaries for fr, es, it, pt, id into _TRANSLATIONS."""
    from src.core.locales import es as _es
    from src.core.locales import fr as _fr
    from src.core.locales import id as _id
    from src.core.locales import it as _it
    from src.core.locales import pt as _pt

    for code, mod in (("fr", _fr), ("es", _es), ("it", _it), ("pt", _pt), ("id", _id)):
        _TRANSLATIONS[code].update(mod.STRINGS)


