_CURRENT_LANG: str = "en"


def _get_settings_file() -> Path:
    return get_config_root() / "app_settings.json"


def load_language_preference() -> str:
    """Temporarily enforce English-only runtime while preserving dictionaries."""
    global _CURRENT_LANG
    _CURRENT_LANG = "en"
    return _CURRENT_LANG


def set_language(lang_code: str) -> None:
    """Temporarily lock language preference to English."""
    global _CURRENT_LANG
    _CURRENT_LANG = "en"
    try:
        p = _get_settings_file()
        data: dict[str, Any] = {}
        if p.exists():
            with open(p, "r", encoding="utf-8") as f:
                data = json.load(f)
        if data.get("language") != "en":
            data["language"] = "en"
            with open(p, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2, ensure_ascii=False)
    except Exception:
        pass


def get_language() -> str:
    """Get current active language code."""
    return _CURRENT_LANG


def t(key: str, default: str = "") -> str:
    """Translate a key into the current language, falling back to English or key itself."""
    lang_dict = _TRANSLATIONS.get(_CURRENT_LANG, _TRANSLATIONS["vi"])
    if key in lang_dict:
        return lang_dict[key]
    en_dict = _TRANSLATIONS.get("en", {})
    if key in en_dict:
        return en_dict[key]
    return default or key


